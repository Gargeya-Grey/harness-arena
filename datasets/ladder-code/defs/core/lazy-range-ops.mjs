import { t } from './_util.mjs';

const task = [
  'An array a of integers starts with the given values and then receives a list of operations.',
  'All indexes are 0-based and inclusive. The operations are ["ADD", l, r, v] (add v to every element a[l..r]), ["SET", l, r, v] (set every element a[l..r] to v), ["SUM", l, r] (answer the sum of a[l..r]) and ["MAX", l, r] (answer the largest element of a[l..r]).',
  'Updates apply in order: a SET replaces whatever earlier ADDs did to those elements, and an ADD after a SET adds to the value that SET wrote.',
  'Before an operation is applied, l is raised to 0 if it is lower and r is lowered to n-1 if it is higher (n is the length of the array).',
  'A range with l > r after that step is empty: an update on an empty range changes nothing, SUM on it answers 0 and MAX on it answers null.',
  'Only SUM and MAX give answers; they are collected in the order of the operations. The array can be empty (n = 0): every range is then empty.',
  'Sizes and limits: n is at most 200000, there are at most 200000 operations, and every initial value and every v has an absolute value of at most 1000.',
  'Compact input. A generator with a seed s (1 to 2147483646) makes a stream of integers: x(0) = s and x(i) = (x(i-1) * 48271) mod 2147483647; the i-th number of the stream is x(i).',
  'values can be {n, seed} instead of an array: the array of n integers whose i-th element (i from 0) is the (i+1)-th stream number mod 2001, minus 1000.',
  'ops can be {count, seed} instead of an array: count operations, which need n of at least 1. Operation j takes the next four numbers of its own stream, p, l, r and v, in this order. Its kind is "ADD", "SET", "SUM" or "MAX" for p mod 4 equal to 0, 1, 2 or 3. With l0 = l mod n and r0 = r mod n its range is from min(l0, r0) to max(l0, r0). Its value is v mod 2001, minus 1000 (SUM and MAX do not use it).',
  'Return the object {count, first, digest}. count is the number of answers. first is the array of the first ten answers (all of them when there are fewer).',
  'digest summarises all answers: start with h = 0 and for each answer in order set h = (h * 1000003 + w) mod 998244353, where w is 0 for a null answer and otherwise w = ((answer mod 998244353) + 998244353) mod 998244353, plus 1.',
].join(' ');

