import { t } from './_util.mjs';

export default {
  name: 'parseDialectCsv',
  signature: 'parseDialectCsv(text) -> array | null',
  kind: 'parsing',
  task: [
    'Parse text in a small CSV dialect and return an array of records; each record is an array of field strings.',
    'Rules.',
    '(1) Fields are separated by a semicolon. A record ends at a line feed (\\n) or at a carriage return plus line feed (\\r\\n).',
    '(2) A field is quoted when its first character is a single quote. A quoted field reads on from the next character: two single quotes in a row stand for one literal single quote, and a single quote that is not followed by another single quote closes the field.',
    'Inside a quoted field every other character is literal, including semicolons, line feeds and carriage returns (a quoted field can span several lines and keeps its line breaks exactly as written).',
    '(3) A single quote anywhere else in a field (not as its first character) is an ordinary character.',
    '(4) After the closing quote the next character must be a semicolon, a record end, or the end of the text; anything else makes the text invalid. A quoted field that is never closed makes the text invalid. For invalid text return null (null for the whole text, not only for one record).',
    '(5) Spaces and tabs are never trimmed. An empty field is the empty string. A bare carriage return that is not followed by a line feed is an ordinary character of an unquoted field.',
    '(6) The empty text gives an empty array. A line that holds nothing is a record with one empty field, so "\\n" gives [[""]]. A record end at the very end of the text does not start another record: "a\\n" gives [["a"]] and "a\\n\\n" gives [["a"],[""]]. A semicolon at the end of a record adds an empty last field: "a;" gives [["a",""]].',
  ].join(' '),
  edges: {
    'doubled-quote': 'two single quotes in a row',
    'multi-line': 'can span several lines',
    'inner-quote': 'anywhere else in a field',
    'after-close': 'anything else makes the text invalid',
    unterminated: 'is never closed',
    'no-trim': 'never trimmed',
    'bare-cr': 'bare carriage return',
    'empty-text': 'The empty text gives',
    'blank-line': 'holds nothing',
    'final-end': 'does not start another record',
    'trailing-semicolon': 'adds an empty last field',
    crlf: 'carriage return plus line feed',
  },
  tests: [
    t('basic', ['a;b;c'], [['a', 'b', 'c']]),
    t('basic', ['a;b\nc;d'], [['a', 'b'], ['c', 'd']]),
    t('crlf', ['a;b\r\nc;d\r\n'], [['a', 'b'], ['c', 'd']]),
    t('doubled-quote', ["'it''s';x"], [["it's", 'x']]),
    t('multi-line', ["'line1\nline2';z\nq"], [['line1\nline2', 'z'], ['q']]),
    t('multi-line', ["'a\r\nb';'c;d'"], [['a\r\nb', 'c;d']]),
    t('inner-quote', ["x'y'z;ab'c"], [["x'y'z", "ab'c"]]),
    t('after-close', ["'a'b;c"], null),
    t('after-close', ["'a' ;b"], null),
    t('unterminated', ["a;'b"], null),
    t('unterminated', ["'abc''"], null),
    t('doubled-quote', ["'';''''"], [['', "'"]]),
    t('no-trim', [" a ;' b '"], [[' a ', ' b ']]),
    t('bare-cr', ['a\rb;c\r'], [['a\rb', 'c\r']]),
    t('empty-text', [''], []),
    t('blank-line', ['a\n\nb\n'], [['a'], [''], ['b']]),
    t('final-end', ['a\n\n'], [['a'], ['']]),
    t('trailing-semicolon', ['a;\n;'], [['a', ''], ['', '']]),
    t('crlf', ["'a'\r\n'b'"], [['a'], ['b']]),
    t('after-close', ["ok;fine\n'bad'x\nlast"], null),
  ],
};
